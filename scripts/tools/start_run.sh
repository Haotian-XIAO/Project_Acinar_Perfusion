#!/bin/bash
# Create a protocol run directory and start one detached run on this machine.
#
# Usage (from anywhere; normally called by launch_remote_run.sh over ssh):
#   start_run.sh --conda-sh FILE --dolfin-mech DIR --study NAME --label LABEL \
#       [--env NAME] [--host-label LABEL] \
#       [run_with_meta.py options: --geometry-file P | --param K=V ...] \
#       -- <target.py> [target args...]
#
# Creates results/<study>/<YYYYMMDD-HHMM>_<label>/ (refuses to reuse it), writes
# STATUS=RUNNING, job.sh and job.pid, launches job.sh under nohup caffeinate -i
# and returns at once. job.sh replaces STATUS by DONE or "FAILED <exit code>";
# exit codes > 128 are signal deaths (e.g. 137 = SIGKILL); once dolfin is imported,
# PETSc catches SIGSEGV/SIGBUS/SIGFPE and exits with 59 ("PETSC ERROR" in run.log).
# run_with_meta.py exits with 2 when a pre-flight check fails (see run_meta.json).
set -euo pipefail

repo=$(cd "$(dirname "$0")/../.." && pwd)
conda_sh= dolfin_mech= study= label= env_name=dolfin_mech host_label=unspecified
meta_args=()
while [ $# -gt 0 ]; do
    case "$1" in
        --conda-sh) conda_sh=$2; shift 2 ;;
        --dolfin-mech) dolfin_mech=$2; shift 2 ;;
        --study) study=$2; shift 2 ;;
        --label) label=$2; shift 2 ;;
        --env) env_name=$2; shift 2 ;;
        --host-label) host_label=$2; shift 2 ;;
        --geometry-file|--param|--manifest) meta_args+=("$1" "$2"); shift 2 ;;
        --) shift; break ;;
        *) echo "start_run.sh: unknown option $1" >&2; exit 64 ;;
    esac
done
[ $# -gt 0 ] || { echo "start_run.sh: missing '-- <target.py> [args]'" >&2; exit 64; }
for name in conda_sh dolfin_mech study label; do
    [ -n "${!name}" ] || { echo "start_run.sh: --${name//_/-} is required" >&2; exit 64; }
done
case "$study$label" in */*|*' '*) echo "start_run.sh: study/label must not contain '/' or spaces" >&2; exit 64 ;; esac

cd "$repo"
if [ -n "$(git status --porcelain)" ]; then
    echo "start_run.sh: refusing to launch, working tree is dirty:" >&2
    git status --short >&2
    exit 65
fi

run_id="$(date +%Y%m%d-%H%M)_$label"
run_rel="results/$study/$run_id"
mkdir -p "results/$study"
mkdir "$run_rel" 2>/dev/null || { echo "start_run.sh: run directory exists, refusing to reuse: $run_rel" >&2; exit 66; }
run_dir="$repo/$run_rel"
echo RUNNING > "$run_dir/STATUS"

q() { printf '%q ' "$@"; }
meta_str=
[ ${#meta_args[@]} -eq 0 ] || meta_str=$(q "${meta_args[@]}")
cat > "$run_dir/job.sh" <<EOF
#!/bin/bash
# Generated by start_run.sh; exact command of this run.
status=$(q "$run_dir/STATUS")
finish() { printf '%s\n' "\$1" > "\$status.tmp" && mv "\$status.tmp" "\$status"; }
trap 'finish "FAILED 129 (job shell got SIGHUP)"; exit 129' HUP
trap 'finish "FAILED 130 (job shell got SIGINT)"; exit 130' INT
trap 'finish "FAILED 143 (job shell got SIGTERM)"; exit 143' TERM
cd $(q "$run_dir")
echo "job start \$(date '+%Y-%m-%d %H:%M:%S %z')"
set +u
source $(q "$conda_sh") && conda activate $(q "$env_name") && export PYTHONPATH=$(q "$dolfin_mech")
rc=\$?
if [ \$rc -eq 0 ]; then
    cd $(q "$repo")
    python scripts/tools/run_with_meta.py --run-dir $(q "$run_rel") --expected-dolfin-mech $(q "$dolfin_mech") \\
        --study $(q "$study") --run-id $(q "$run_id") --host-label $(q "$host_label") ${meta_str}-- $(q "$@")
    rc=\$?
    cd $(q "$run_dir")
else
    echo "environment setup failed (exit \$rc)"
fi
echo "job end \$(date '+%Y-%m-%d %H:%M:%S %z') exit \$rc"
if [ \$rc -eq 0 ]; then finish DONE; else finish "FAILED \$rc"; fi
exit \$rc
EOF

nohup caffeinate -i /bin/bash "$run_dir/job.sh" > "$run_dir/run.log" 2>&1 < /dev/null &
pid=$!
echo "$pid" > "$run_dir/job.pid"
echo "run_dir=$run_rel"
echo "run_id=$run_id"
echo "pid=$pid"
